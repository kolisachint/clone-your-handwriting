# ---------------------------------------------------------------- ios

PROFILE_ID = "com.annahand.fonts"


def build_ios(fams, out):
    out.mkdir(parents=True, exist_ok=True)
    payloads = []
    for fam in fams:
        ttf = fam.file("ttf")
        payloads.append({
            "Name": ttf.name,
            "PayloadContent": ttf.read_bytes(),
            "PayloadDescription": f"{fam.name} font",
            "PayloadDisplayName": fam.name,
            "PayloadIdentifier": f"com.annahand.font.{fam.name}",
            "PayloadType": "com.apple.font",
            "PayloadUUID": str(uuid.uuid4()),
            "PayloadVersion": 1,
        })
    profile = {
        "PayloadContent": payloads,
        "PayloadDescription": "Installs the AnnaHand handwriting fonts.",
        "PayloadDisplayName": "AnnaHand fonts",
        "PayloadIdentifier": PROFILE_ID,
        "PayloadRemovalDisallowed": False,
        "PayloadType": "Configuration",
        "PayloadUUID": str(uuid.uuid4()),
        "PayloadVersion": 1,
    }
    data = plistlib.dumps(profile, fmt=plistlib.FMT_XML, sort_keys=True)
    plistlib.loads(data)  # fail early if the profile is not valid plist
    (out / "AnnaHand.mobileconfig").write_bytes(data)
    write_readme(out, ios_readme(fams))


