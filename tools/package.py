# ---------------------------------------------------------------- zips

def zip_dir(src, zip_path, arc_root):
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(src.rglob("*")):
            if p.is_file():
                rel = p.relative_to(src).as_posix()
                zf.write(p, f"{arc_root}/{rel}")
    return zip_path


def build_zips():
    made = []
    for surface in SURFACES:
        made.append(zip_dir(DIST / surface,
                            DIST / f"AnnaHand-{surface}.zip",
                            f"AnnaHand-{surface}"))
    all_zip = DIST / "AnnaHand-all.zip"
    with zipfile.ZipFile(all_zip, "w", zipfile.ZIP_DEFLATED) as zf:
        for surface in SURFACES:
            base = DIST / surface
            for p in sorted(base.rglob("*")):
                if p.is_file():
                    rel = p.relative_to(base).as_posix()
                    zf.write(p, f"AnnaHand-all/{surface}/{rel}")
    made.append(all_zip)
    return made


# ---------------------------------------------------------------- main

def main():
    fams = read_families()
    print("families:", ", ".join(f.name for f in fams))
    reset_dist()

    build_web(fams, DIST / "web")
    build_desktop(fams, DIST / "desktop")
    build_ios(fams, DIST / "ios")
    build_android(fams, DIST / "android")
    build_office(fams, DIST / "office")
    build_design(fams, DIST / "design")

    zips = build_zips()
    print("built:")
    for z in zips:
        print(f"  {z.relative_to(ROOT)}  {z.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
