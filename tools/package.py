#!/usr/bin/env python3
"""Build dist/: one ready-to-use bundle per surface, plus zips.

Run from the repo root:

    /tmp/hfv/bin/python tools/package.py

It reads whatever is in fonts/<Family>/ and rebuilds dist/ from scratch.
Needs fonttools with woff/woff2 support (pip install "fonttools[woff]").
"""

import html
import plistlib
import shutil
import sys
import uuid
import zipfile
from dataclasses import dataclass
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "fonts"
DIST = ROOT / "dist"

SURFACES = ["web", "desktop", "ios", "android", "office", "design"]

# Order used everywhere (demo, README lists, profile).
ORDER = ["AnnaHand", "AnnaHandPaper", "AnnaHandTyped", "AnnaHandAccess"]

BLURBS = {
    "AnnaHand": "Handwritten. Your strokes as written, stray ink removed.",
    "AnnaHandPaper": "One even pen line, like a gel pen.",
    "AnnaHandTyped": "Smoothed and lighter, with more space. For long text.",
    "AnnaHandAccess": "Bold, wide spacing, slashed zero. "
    "For low vision and small screens.",
}

SAMPLE = (
    "Dear reader, this is a sample of the font written in my own "
    "handwriting. It should stay easy to read at a comfortable size. "
    "The quick brown fox jumps over the lazy dog. 0123456789."
)


@dataclass
class Family:
    name: str  # install / CSS family name, e.g. AnnaHandTyped
    folder: Path  # fonts/<name>/
    stem: str  # primary file base name, e.g. AnnaHandTyped-Regular

    def file(self, ext):
        p = self.folder / f"{self.stem}.{ext}"
        return p if p.exists() else None

    def files(self, ext):
        return sorted(self.folder.glob(f"*.{ext}"))

    def source(self):
        """Best outline file to convert from (ttf first, then otf)."""
        return self.file("ttf") or self.file("otf")


def read_families():
    fams = []
    for folder in sorted(p for p in FONTS.iterdir() if p.is_dir()):
        outlines = sorted(folder.glob("*.ttf")) + sorted(folder.glob("*.otf"))
        if not outlines:
            continue
        regular = [p for p in outlines if p.stem.endswith("-Regular")]
        stem = (regular or outlines)[0].stem
        fams.append(Family(folder.name, folder, stem))
    fams.sort(key=lambda f: (ORDER.index(f.name) if f.name in ORDER else 99,
                             f.name))
    if not fams:
        sys.exit("No font families found in fonts/.")
    for fam in fams:
        for ext in ("ttf", "otf"):
            if fam.file(ext) is None:
                sys.exit(f"{fam.name}: missing {fam.stem}.{ext}")
        names = TTFont(fam.file("ttf"))["name"]
        family_name = names.getDebugName(1)
        if family_name != fam.name:
            print(f"warning: {fam.name} folder, but font says {family_name}")
    return fams


def cmap_codepoints(fam):
    return sorted(TTFont(fam.source()).getBestCmap())


def to_ranges(codepoints):
    """[0x20, 0x21, 0x22, 0x41] -> 'U+0020-0022, U+0041'."""
    runs = []
    for cp in codepoints:
        if runs and cp == runs[-1][1] + 1:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp])
    parts = []
    for a, b in runs:
        parts.append(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}")
    return parts


def wrap_list(items, width=72, indent="    ", sep=", "):
    lines, line = [], ""
    for item in items:
        piece = item + sep
        if line and len(indent + line + piece) > width:
            lines.append(indent + line.rstrip())
            line = ""
        line += piece
    if line:
        lines.append(indent + line.rstrip(" ,"))
    return "\n".join(lines)


def reset_dist():
    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir(parents=True)


def copy_files(paths, out):
    out.mkdir(parents=True, exist_ok=True)
    for p in paths:
        shutil.copy2(p, out / p.name)


def write_readme(out, text):
    (out / "README.md").write_text(text.strip() + "\n", encoding="utf-8")


def file_list(paths):
    return "\n".join(f"- {p.name}" for p in paths)


def family_list(fams):
    return "\n".join(f"- {f.name}" for f in fams)


# ---------------------------------------------------------------- web

def fonts_css(fams):
    blocks = [
        "/* AnnaHand web fonts. Generated by tools/package.py.",
        "   Keep this file in the same folder as the font files. */",
    ]
    for fam in fams:
        cps = cmap_codepoints(fam)
        if not cps:
            sys.exit(f"{fam.name}: font has no characters")
        ranges = wrap_list(to_ranges(cps), sep=", ")
        blocks.append(
            "\n".join([
                "",
                "@font-face {",
                f'  font-family: "{fam.name}";',
                f'  src: url("{fam.stem}.woff2") format("woff2"),',
                f'       url("{fam.stem}.woff") format("woff");',
                "  font-weight: 400;",
                "  font-style: normal;",
                "  font-display: swap;",
                "  unicode-range:",
                ranges.rstrip(",") + ";",
                "}",
            ])
        )
    return "\n".join(blocks) + "\n"


def demo_html(fams):
    sections = []
    for fam in fams:
        visible = [chr(cp) for cp in cmap_codepoints(fam)
                   if cp > 0x20 and not 0x7F <= cp < 0xA0]
        charset = " ".join(html.escape(c) for c in visible)
        blurb = html.escape(BLURBS.get(fam.name, ""))
        name = html.escape(fam.name)
        sections.append(f"""
  <section>
    <h2 style='font-family: "{name}", system-ui, sans-serif;'>{name}</h2>
    <p class="note">{blurb}</p>
    <p class="sample" style='font-family: "{name}", system-ui, sans-serif;'>
      {html.escape(SAMPLE)}
    </p>
    <p class="label">Full character set</p>
    <p class="charset" style='font-family: "{name}", system-ui, sans-serif;'>
      {charset}
    </p>
  </section>""")
    body = "\n".join(sections)
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>AnnaHand font demo</title>
  <link rel="stylesheet" href="./fonts.css">
  <style>
    :root {{ color-scheme: light; }}
    body {{
      margin: 0;
      background: #ffffff;
      color: #111111;
      font-family: system-ui, sans-serif;
      font-size: 22px;
      line-height: 1.6;
    }}
    main {{ max-width: 44rem; margin: 0 auto; padding: 2rem 1.25rem 4rem; }}
    h1 {{ font-size: 2.5rem; margin: 0 0 0.5rem; }}
    h2 {{
      font-size: 2rem;
      margin: 3rem 0 0.25rem;
      padding-top: 1rem;
      border-top: 3px solid #111111;
    }}
    .note {{ font-size: 1.2rem; color: #222222; margin: 0.25rem 0 0; }}
    .sample {{ font-size: 2.2rem; line-height: 1.5; margin: 1rem 0; }}
    .label {{ font-size: 1.2rem; font-weight: 700; margin: 1.5rem 0 0.25rem; }}
    .charset {{
      font-size: 2.2rem;
      line-height: 1.8;
      letter-spacing: 0.06em;
      word-break: break-word;
    }}
  </style>
</head>
<body>
<main>
  <h1>AnnaHand</h1>
  <p>Four handwriting styles. Each one shows a sample and every character.</p>
{body}
</main>
</body>
</html>
"""


def web_readme(fams):
    return f"""
# AnnaHand for websites

Web fonts for four styles. Open demo.html to see them.

## Files

- fonts.css: the @font-face rules for all styles
- *.woff2 and *.woff: the font files
- demo.html: a page that shows every style

## Styles

{family_list(fams)}

## Add to your page

1. Copy this whole folder to your site, for example /fonts/.
2. Put this in the head of your page:

    <link rel="stylesheet" href="fonts/fonts.css">

3. Use a font in your CSS:

    body {{
      font-family: "AnnaHandTyped", "Comic Neue", system-ui, sans-serif;
    }}

Write the name in quotes, exactly as in the list above.

## Preload (faster first paint)

Put this after the stylesheet link. Change the path to match your site:

    <link rel="preload" href="fonts/AnnaHandTyped-Regular.woff2"
          as="font" type="font/woff2" crossorigin>

Preload only the style the page uses first.

## Fallback stack with a CSS variable

    :root {{
      --font-hand: "AnnaHandTyped", "Comic Neue", system-ui, sans-serif;
    }}
    body {{
      font-family: var(--font-hand);
    }}

If the font is missing, the browser uses the next name in the list.

## Notes

- font-display: swap shows text at once in a fallback font, then switches.
- Each @font-face has a unicode-range: the characters the font has.
  Any other character comes from the next font in the stack.
- If you move the files, keep fonts.css and the font files together.
"""


def build_web(fams, out):
    out.mkdir(parents=True, exist_ok=True)
    for fam in fams:
        copy_files(fam.files("woff2") + fam.files("woff"), out)
        for ext in ("woff2", "woff"):
            target = out / f"{fam.stem}.{ext}"
            if not target.exists():
                print(f"making {target.name} from {fam.source().name}")
                font = TTFont(fam.source())
                font.flavor = ext
                font.save(target)
    (out / "fonts.css").write_text(fonts_css(fams), encoding="utf-8")
    (out / "demo.html").write_text(demo_html(fams), encoding="utf-8")
    write_readme(out, web_readme(fams))


